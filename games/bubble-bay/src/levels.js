// What each area mixes in, introduced gently.
const SPECIALS_FROM = { rainbow: 6, stone: 14, ice: 27, bomb: 40, zap: 53 };

const GOALS_FIRST = ['pop', 'otters', 'pop', 'otters', 'otters', 'pop', 'otters', 'pop', 'otters', 'otters', 'pop', 'otters', 'otters'];
const GOALS_LATER = ['otters', 'anchor', 'pop', 'otters', 'otters', 'anchor', 'pop', 'otters', 'anchor', 'otters', 'pop', 'anchor', 'otters'];

const SHAPES = ['rows', 'stalactite', 'vines', 'wave', 'columns', 'diamond', 'bridge', 'arch', 'heart', 'zigzag'];
const ANCHOR_SHAPES = ['stalactite', 'vines', 'bridge', 'diamond'];

// Shape masks: is cell (r, x) filled, for a board `rows` deep?
const SHAPE_FN = {
  rows: () => true,
  stalactite: (r, x, rows) => Math.abs(x - W) <= W - 0.5 - (r / Math.max(1, rows - 1)) * (W - 2.6),
  vines: (r, x, rows, phase) => {
    if (r === 0) return true;
    const stems = [4, 10, 16];
    return stems.some((sx, k) => {
      const reach = r <= 2 ? 1 : 3 + ((k + phase) % 2);
      return Math.abs(x - sx) <= reach && r < rows - ((k + phase) % 2);
    });
  },
  wave: (r, x, rows, phase) => r <= rows - 1 - Math.round(1.6 * (1 + Math.sin(x * 0.5 + phase))),
  columns: (r, x, rows, phase) => r === 0 || Math.floor((x + 1 + (phase % 2) * 2) / 4) % 2 === 0,
  diamond: (r, x, rows) => Math.abs(x - W) / (W - 0.2) + Math.abs(r - (rows - 1) / 2) / (rows / 2 + 0.6) <= 1.05,
  bridge: (r, x) => r === 0 || (r <= 2 ? x <= 4 || x >= 16 : true),
  arch: (r, x, rows) => r < 2 || !(Math.abs(x - W) < (r - 1) * 1.6),
  heart: (r, x, rows) => {
    const nx = (x - W) / (W - 1) * 1.25;
    const ny = 1.05 - (r / Math.max(1, rows - 1)) * 2.1;
    const a = nx * nx + ny * ny - 1;
    return a * a * a - nx * nx * ny * ny * ny <= 0.05 || r === 0;
  },
  zigzag: (r, x, rows, phase) => r === 0 || ((Math.floor((x + r * 2 + phase) / 4) % 2 === 0) && r < rows) || r === rows - 1,
};

