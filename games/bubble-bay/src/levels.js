// Fallback for untuned levels: a rough, generous estimate.
export function supplyFor(stats) {
  return Math.ceil(stats.bubbles * 0.6 + stats.colors * 2 + 8);
}

// Each area deals the shapes out in its own shuffled order.
const AREA_SHAPES = [0, 1, 2, 3, 4].map((area) => new Rng(hashSeed(area, 0x5ea)).shuffle(SHAPES.slice()));

function pickShape(id, area, within, rng, goal) {
  if (id === 1) return 'rows';
  if (goal === 'anchor') return ANCHOR_SHAPES[(within + area + rng.int(2)) % ANCHOR_SHAPES.length];
  if (!id) return SHAPES[rng.int(SHAPES.length)];
  return AREA_SHAPES[area][within % SHAPES.length];
}

// Builds one level from a few parameters. `within` is its place in the area
// (0..12) and drives difficulty.
export function buildLevel({ id, area, within, seed, goal, name, daily = false }) {
  const rng = new Rng(seed);
  const order = id || area * PER_AREA + within + 1; // difficulty ladder
  const rows = Math.min(8, area === 0 ? 5 + Math.floor(within / 3) : 6 + Math.floor(within / 4) + (area >= 3 ? 1 : 0));
  let colors;
  if (area === 0) colors = within < 5 ? 3 : 4;
  else if (area === 1) colors = 4;
  else if (area === 2) colors = within < 6 ? 4 : 5;
  else colors = 5;
  const shape = pickShape(id, area, within, rng, goal);
  const phase = rng.int(4);

  // 1. the mask
  const cells = new Array(SIZE).fill(null);
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols(r); c++) {
      const i = index(r, c);
      if (SHAPE_FN[shape](r, CX[i], rows, phase)) cells[i] = { k: 'b', c: 0 };
    }
  }
  const board = new Board(cells);
  for (const i of board.floating()) cells[i] = null;

  // 2. colors in small friendly clumps that never touch a clump of their own color
  const filled = [];
  for (let i = 0; i < SIZE; i++) if (cells[i]) filled.push(i);
  const color = new Int8Array(SIZE).fill(-1);
  const bigClumps = Math.max(0, 0.7 - order * 0.012);
  for (const start of filled) {
    if (color[start] >= 0) continue;
    const target = 2 + rng.int(2) + (rng.next() < bigClumps ? 1 : 0);
    const clump = [start];
    color[start] = 99;
    for (let k = 0; k < clump.length && clump.length < target; k++) {
      const options = NEIGHBORS[clump[k]].filter((n) => cells[n] && color[n] < 0);
      rng.shuffle(options);
      for (const n of options) {
        if (clump.length >= target) break;
        color[n] = 99;
        clump.push(n);
      }
    }
    const touching = new Set();
    for (const i of clump) for (const n of NEIGHBORS[i]) if (color[n] >= 0 && color[n] < 99) touching.add(color[n]);
    const allowed = [];
    for (let c = 0; c < colors; c++) if (!touching.has(c)) allowed.push(c);
    const pick = allowed.length ? rng.pick(allowed) : rng.int(colors);
    for (const i of clump) color[i] = pick;
  }
  for (const i of filled) cells[i] = { k: 'b', c: color[i] };
  // make sure every color shows up
  for (let c = 0; c < colors; c++) {
    if (!filled.some((i) => cells[i].c === c)) {
      const i = filled[rng.int(filled.length)];
      cells[i] = { k: 'b', c };
    }
  }

  const reserved = new Set();
  const free = () => filled.filter((i) => cells[i] && cells[i].k === 'b' && !reserved.has(i));
  const reserveAround = (i, radius = 1) => {
    reserved.add(i);
    if (radius >= 1) for (const n of NEIGHBORS[i]) reserved.add(n);
  };

  // 3. the anchor hangs at the bottom tip
  let anchorAt = -1;
  if (goal === 'anchor') {
    let best = -1;
    let bestScore = -Infinity;
    const want = Math.max(2, Math.round(rows * 0.55));
    for (const i of filled) {
      const r = rowOf(i);
      if (r < 2) continue;
      const score = -Math.abs(r - want) * 10 - Math.abs(CX[i] - W) + rng.next();
      if (score > bestScore) { bestScore = score; best = i; }
    }
    anchorAt = best;
    cells[anchorAt] = { k: 'anchor' };
    reserveAround(anchorAt, 1);
  }

  // 4. otters near the top
  const otterCount = goal === 'otters' ? Math.min(6, 2 + Math.floor(within / 3) + (area >= 2 ? 1 : 0)) : (within % 3 === 1 ? 1 : 0);
  const otters = [];
  for (let k = 0; k < otterCount; k++) {
    // tucked in: every neighbor is a bubble, so the player has to dig
    const tucked = (i) => NEIGHBORS[i].every((n) => cells[n]);
    let spots = free().filter((i) => rowOf(i) <= Math.min(2, rows - 2) && tucked(i) && !NEIGHBORS[i].some((n) => cells[n]?.k === 'otter'));
    if (spots.length < otterCount - k) spots = free().filter((i) => rowOf(i) <= Math.min(2, rows - 2) && !NEIGHBORS[i].some((n) => cells[n]?.k === 'otter'));
    if (!spots.length) break;
    // spread them out left to right
    spots.sort((a, b) => CX[a] - CX[b] || a - b);
    const lane = Math.floor(((k + 0.5) / otterCount) * spots.length);
    const i = spots[Math.min(spots.length - 1, Math.max(0, lane + rng.int(3) - 1))];
    cells[i] = { k: 'otter', o: 0 };
    otters.push(i);
    reserved.add(i);
  }

  // 5. specials
  const ladder = id || area * PER_AREA + within + 1;
  const allow = (kind) => ladder >= SPECIALS_FROM[kind];
  let bottom = 0;
  for (const i of filled) bottom = Math.max(bottom, rowOf(i));
  const sprinkle = (count, make, rowMin = 1) => {
    for (let k = 0; k < count; k++) {
      const spots = free().filter((i) => rowOf(i) >= rowMin);
      if (!spots.length) return;
      const i = spots[rng.int(spots.length)];
      cells[i] = make(cells[i]);
      reserved.add(i);
    }
  };
  if (allow('stone')) sprinkle(Math.min(6, 2 + Math.floor(within / 3)), () => ({ k: 'stone' }), 1);
  if (allow('ice')) sprinkle(Math.min(10, 3 + Math.floor(within / 2)), (cell) => ({ k: 'ice', c: cell.c, hp: 2 }), 1);
  // blasters sit low, so they help dig rather than cut the whole board loose
  if (allow('bomb')) sprinkle(1 + (within % 2), () => ({ k: 'bomb' }), Math.max(2, bottom - 2));
  if (allow('zap')) sprinkle(1 + (within % 3 === 0 ? 1 : 0), () => ({ k: 'zap' }), Math.max(2, bottom - 1));
  if (allow('rainbow')) sprinkle(1 + (within % 3 === 2 ? 1 : 0), () => ({ k: 'rainbow' }), 1);

  // keep every color on the board after specials
  const present = new Set(cells.filter((cell) => cell && (cell.k === 'b' || cell.k === 'ice')).map((cell) => cell.c));
  for (let color = 0; color < colors; color++) {
    if (present.has(color)) continue;
    const spot = free()[0];
    if (spot !== undefined) cells[spot] = { k: 'b', c: color };
  }

  const bubbles = cells.filter((cell) => cell && cell.k !== 'otter' && cell.k !== 'anchor').length;
  const stats = { bubbles, colors, otters: otters.length, rows };
  let need = 0;
  if (goal === 'otters') need = otters.length;
  else if (goal === 'pop') need = Math.max(10, Math.round((bubbles * 0.8) / 5) * 5);
  else need = 1;

  const tuned = !daily && TUNING[id - 1];
  const supply = tuned ? tuned[0] : supplyFor(stats);
  const creep = Math.max(5, AREAS[area].creep - (within >= 9 ? 1 : 0));
  return {
    id,
    area,
    within,
    name: name || AREAS[area].names[within % PER_AREA],
    daily,
    seed,
    shape,
    colors,
    rows,
    goal: { type: goal, need },
    supply,
    creep,
    stars: tuned ? [0, tuned[1], tuned[2]] : [0, Math.max(2, Math.round(supply * 0.15)), Math.max(4, Math.round(supply * 0.3))],
    tuned: !!tuned,
    cells: cells.slice(),
    otters,
    anchor: anchorAt,
  };
}

function levelParams(id) {
  const area = Math.floor((id - 1) / PER_AREA);
  const within = (id - 1) % PER_AREA;
  const goal = area === 0 ? GOALS_FIRST[within] : GOALS_LATER[within];
  return { id, area, within, goal, seed: hashSeed(id, 0xb0bb1e) };
}

// Otters get names in order of appearance, so the whole collection turns up
// well before the end of the map.
function nameOtters(levels) {
  let slot = 0;
  for (const level of levels) {
    for (const i of level.otters) {
      level.cells[i] = { k: 'otter', o: slot % OTTER_COUNT };
      slot++;
    }
  }
}

export const LEVELS = [];
for (let id = 1; id <= LEVEL_COUNT; id++) LEVELS.push(buildLevel(levelParams(id)));
nameOtters(LEVELS);

export function getLevel(id) {
  return LEVELS[Math.max(1, Math.min(LEVEL_COUNT, id | 0)) - 1];
}

export function freshBoard(level) {
  return new Board(level.cells.slice(), 0);
}

// ------------------------------------------------------------- daily

export function dateKeyOf(date = new Date()) {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, '0');
  const d = String(date.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

export function seedOfKey(key) {
  let h = 2166136261 >>> 0;
  for (let k = 0; k < key.length; k++) {
    h ^= key.charCodeAt(k);
    h = Math.imul(h, 16777619) >>> 0;
  }
  return hashSeed(h, 0xda11);
}

const DAILY_GOALS = ['otters', 'pop', 'anchor', 'otters', 'pop', 'otters', 'anchor'];

export function dailyLevel(key) {
  const seed = seedOfKey(key);
  const rng = new Rng(seed);
  const area = rng.int(AREAS.length);
  const within = 4 + rng.int(6);
  const goal = DAILY_GOALS[rng.int(DAILY_GOALS.length)];
  const level = buildLevel({ id: 0, area, within, seed, goal, name: 'Daily Tide', daily: true });
  level.dateKey = key;
  for (const i of level.otters) level.cells[i] = { k: 'otter', o: rng.int(OTTER_COUNT) };
  return level;
}

