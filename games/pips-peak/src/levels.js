/** Abilities Pip has unlocked by the time this level starts. */
export function abilitiesFor(level) {
  return ZONES[level.zone].abilities;
}

/** Look a level up by id, or by 1-based number when given a number. */
export function findLevel(key) {
  if (typeof key === 'number') return LEVELS[key - 1] || null;
  return LEVELS.find((level) => level.id === key) || null;
}

/** Levels grouped by zone, for the level-select map. */
export function levelsByZone() {
  return ZONES.map((zone, index) => ({
    zone,
    index,
    levels: LEVELS.filter((level) => level.zone === index),
  }));
}
