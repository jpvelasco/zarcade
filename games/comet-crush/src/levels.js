export const LEVELS = [];
CONSTELLATIONS.forEach((c, ci) => {
  SHAPES[ci].forEach((s, li) => {
    LEVELS.push({ index: LEVELS.length, c: ci, n: li, name: s.name, rows: pad(s.rows, s.before || 0), boss: null });
  });
  const b = BOSS_LEVELS[ci];
  LEVELS.push({ index: LEVELS.length, c: ci, n: 5, name: b.name, rows: b.rows, boss: b.boss });
});

export const LEVELS_PER_CONSTELLATION = 6;

export function levelLabel(index) {
  const l = LEVELS[index];
  return l.boss ? `${l.c + 1}-★` : `${l.c + 1}-${l.n + 1}`;
}

// Moving bricks slide ±MOVE.amp around their home cell.
export const MOVE = { amp: GRID.bw * 1.5, speed: 1.1 };

// Expand a level layout into brick and portal cells.
export function parseLevel(level) {
  const cells = [];
  const portals = {};
  level.rows.forEach((row, r) => {
    [...row].forEach((ch, c) => {
      if (ch === '.') return;
      if (ch === 'A' || ch === 'B') portals[ch] = { col: c, row: r };
      else cells.push({ col: c, row: r, ch });
    });
  });
  return { cells, portals };
}

export const isBreakable = (ch) => ch !== 'M' && ch !== '.' && ch !== 'A' && ch !== 'B';
