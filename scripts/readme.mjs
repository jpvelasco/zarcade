// Rebuilds the cabinet gallery in README.md from the arcade manifest, so the
// README never lists a stale set of games. Run `npm run readme` after adding,
// renaming or removing a game; scripts/tests/readme.test.mjs fails until you do.
import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const { GAMES } = require(join(ROOT, 'arcade/games.js'));
const { SHELVES, shelfOf } = require(join(ROOT, 'arcade/logic.js'));

export const START = '<!-- cabinets:start — generated by `npm run readme` from arcade/games.js; edit the manifest, not this block -->';
export const END = '<!-- cabinets:end -->';
const PER_ROW = 4;

// A little sign over each shelf of the gallery.
const SHELF_ICONS = {
  'Action & Adventure': '🗺️',
  Racing: '🏁',
  'Puzzle & Word': '🧩',
  'Arcade & Party': '🕹️',
  Cozy: '🍵',
  'Strategy & Sports': '🏆',
};

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function cell(g) {
  const href = `games/${g.slug}/`;
  return `<td align="center" valign="top" width="${100 / PER_ROW}%"><a href="${href}"><img src="games/${g.slug}/cover.svg" alt="${esc(g.title)}" width="200"></a><br><b><a href="${href}">${esc(g.title)}</a></b><br><sub>${esc(g.tagline)}</sub></td>`;
}

export function cabinets(games = GAMES) {
  const out = [START];
  for (const [shelf] of SHELVES) {
    const list = games.filter((g) => shelfOf(g.genre) === shelf);
    if (!list.length) continue;
    out.push('', `### ${SHELF_ICONS[shelf] || '🎮'} ${shelf}`, '', '<table>');
    for (let i = 0; i < list.length; i += PER_ROW) {
      out.push('<tr>', ...list.slice(i, i + PER_ROW).map(cell), '</tr>');
    }
    out.push('</table>');
  }
  out.push('', END);
  return out.join('\n');
}

// Replace the generated block in a README's text (markers must already exist).
export function withCabinets(text, games = GAMES) {
  const a = text.indexOf(START);
  const b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error('README.md is missing the cabinets markers');
  return text.slice(0, a) + cabinets(games) + text.slice(b + END.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const path = join(ROOT, 'README.md');
  const before = await readFile(path, 'utf8');
  const after = withCabinets(before);
  if (after === before) console.log('README.md cabinets are already up to date.');
  else {
    await writeFile(path, after);
    console.log(`README.md cabinets rebuilt: ${GAMES.length} games.`);
  }
}
